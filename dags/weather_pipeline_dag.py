
import csv
from datetime import datetime
from pathlib import Path

import pendulum
from airflow import DAG
from airflow.operators.bash import BashOperator
from airflow.operators.python import PythonOperator

# Expected output from the PySpark ETL script.
CSV_PATH = Path("/opt/airflow/data/combined_weather.csv")

EXPECTED_COLUMNS = [
    "location_id",
    "date_text",
    "temp_mean_text",
    "temp_max_text",
    "temp_min_text",
    "precip_text",
    "rain_text",
    "snowfall_text",
]

NUMERIC_COLUMNS = [
    "temp_mean_text",
    "temp_max_text",
    "temp_min_text",
    "precip_text",
    "rain_text",
    "snowfall_text",
]


#Task 2: Validate the CSV generated by PySpark.
def validate_weather_data():
    if not CSV_PATH.exists():
        raise FileNotFoundError(
            f"Combined weather CSV was not found: {CSV_PATH}"
        )

    row_count = 0
    seen_records = set()

    with CSV_PATH.open("r", newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)

        #Check the column headers.
        if reader.fieldnames != EXPECTED_COLUMNS:
            raise ValueError(
                f"Unexpected CSV columns: {reader.fieldnames}"
            )

        for row in reader:
            row_count += 1

            #Check for missing values.
            for column, value in row.items():
                if value is None or not value.strip():
                    raise ValueError(
                        f"Missing value in row {row_count}, "
                        f"column '{column}'"
                    )

            #Check the location ID.
            try:
                location_id = int(row["location_id"])
            except ValueError as error:
                raise ValueError(
                    f"Invalid location ID in row {row_count}"
                ) from error

            #Check the date format.
            try:
                datetime.strptime(row["date_text"], "%m/%d/%Y")
            except ValueError as error:
                raise ValueError(
                    f"Invalid date in row {row_count}: {row['date_text']}"
                ) from error

            #Check that weather measurements are numeric.
            for column in NUMERIC_COLUMNS:
                try:
                    float(row[column])
                except ValueError as error:
                    raise ValueError(
                        f"Non-numeric value in row {row_count}, "
                        f"column '{column}'"
                    ) from error

            #Check for duplicate location/date records.
            record_key = (location_id, row["date_text"])

            if record_key in seen_records:
                raise ValueError(
                    f"Duplicate location/date record: {record_key}"
                )

            seen_records.add(record_key)

    #Check that the CSV contains records.
    if row_count == 0:
        raise ValueError("The combined CSV contains no data rows.")

    print(f"Validation passed. Rows checked: {row_count}") #print how many records were checked


#Create the DAG "weather_pipeline"
with DAG(
    dag_id="weather_pipeline",
    description="Combine, validate, and load historical weather data",
    schedule=None,
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    tags=["weather", "capstone"],
) as dag:

    # Task 1: Run the PySpark ETL script.
    run_weather_etl = BashOperator(
        task_id="run_weather_etl",
        bash_command="python /opt/airflow/scripts/Main.py",
    )

    # Task 2: Validate the generated CSV by caalling validate_weather_data() to check everything
    validate_data = PythonOperator(
        task_id="validate_weather_data",
        python_callable=validate_weather_data,
    )

    # Task 3: Load the validated CSV into Snowflake.
    load_to_snowflake = BashOperator(
        task_id="load_to_snowflake",
        bash_command=(
            "python /opt/airflow/scripts/load_weather_to_snowflake.py"
        ),
    )

    #Run tasks in order.
    run_weather_etl >> validate_data >> load_to_snowflake
